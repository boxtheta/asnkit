"""Makes the text of a Python module from a compiled ASN.1 specification.

The module imports asnkit, has the ``.asni`` file in it as bytes and has
a data class for each SEQUENCE and SET, an enumeration for each
ENUMERATED and a class for each alternative of a CHOICE, with methods
to encode and decode them and to turn them into and from what asnkitrt
encodes and decodes.

"""

import keyword
import re
from typing import Any

from asnkitrt import syntax

DEFAULT_CODEC = "ber"

# What asnkitrt encodes and decodes a type as, by the name of the type.
# Everything else is a SEQUENCE, a SET, a SEQUENCE OF, a SET OF, a CHOICE,
# an ENUMERATED or the name of a type.
PLAIN_TYPES = {
    "BOOLEAN": "bool",
    "INTEGER": "int",
    "REAL": "float",
    "OCTET STRING": "bytes",
    "BIT STRING": "tuple[bytes, int]",
    "NULL": "None",
    "OBJECT IDENTIFIER": "str",
    "RELATIVE-OID": "str",
    "ObjectDescriptor": "str",
    "TeletexString": "str",
    "VideotexString": "str",
    "NumericString": "str",
    "PrintableString": "str",
    "IA5String": "str",
    "VisibleString": "str",
    "GeneralString": "str",
    "UTF8String": "str",
    "BMPString": "str",
    "GraphicString": "str",
    "UniversalString": "str",
    "UTCTime": "datetime.datetime",
    "GeneralizedTime": "datetime.datetime",
    "DATE-TIME": "datetime.datetime",
    "DATE": "datetime.date",
    "TIME-OF-DAY": "datetime.time",
    "DURATION": "str",
    "ANY": "Any",
    "ANY DEFINED BY": "Any",
    "OpenType": "Any",
    "EXTERNAL": "Any",
}

# What the generated code uses, which a type is not called.
TAKEN = {
    "Any",
    "ClassVar",
    "CodecType",
    "DEFAULT_CODEC",
    "TypeAlias",
    "asnkit",
    "dataclasses",
    "datetime",
    "enum",
    "functools",
    "spec",
    "use_asni",
}

# Names of what the methods of the classes are called, which a member
# can not be called.
RESERVED = {"encode", "decode", "to_value", "from_value"}


class GenerateError(Exception):
    pass


def camel(name: str) -> str:
    """``foo-bar`` and ``foo_bar`` are ``FooBar``."""

    parts = [part for part in re.split(r"[-_]", name) if part]
    result = "".join(part[0].upper() + part[1:] for part in parts)

    if not result or result[0].isdigit():
        result = "T" + result

    return result


def snake(name: str) -> str:
    """``fooBar`` and ``foo-bar`` are ``foo_bar``."""

    name = name.replace("-", "_")
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = name.lower()

    if not name or name[0].isdigit():
        name = "n" + name

    return name


def field_name(name: str) -> str:
    result = snake(name)

    if keyword.iskeyword(result) or result in RESERVED or result.startswith("_"):
        result += "_"

    return result


HEADER = '''\
# Generated by asnkit-gen-python {version} from {sources}. Do not edit.
#
# This file is made from the specification it names, and needs the asnkitrt
# package (MIT) to run. It may be used under terms of your choice: the code
# that asnkit-gen-python copies into it is not under the Apache License of
# the plugin.

from __future__ import annotations

import dataclasses
import datetime
import enum
import functools
from typing import Any, ClassVar, TypeAlias

import asnkitrt
from asnkitrt.runtime import CodecType

DEFAULT_CODEC: CodecType = "{codec}"

{load}


def _type(codec: CodecType, asn1_type: tuple[str, str]) -> Any:
    if not asn1_type[1]:
        raise TypeError(
            "This type is a part of another type, and is not encoded on its own."
        )

    return spec(codec).modules[asn1_type[0]][asn1_type[1]]


def _to_value(shape: Any, obj: Any) -> Any:
    """What asnkitrt encodes, for an object of given shape."""

    if shape is None:
        return obj

    if isinstance(shape, type):
        shape = getattr(shape, "_shape")

    kind = shape[0]

    if kind == "seq":
        values: dict[str, Any] = {{}}

        for attribute, name, member_shape, how in shape[2]:
            member = getattr(obj, attribute)

            if how == "null":
                # An optional NULL is there if it is True.
                if member:
                    values[name] = None
            elif how == "required_null":
                values[name] = None
            elif member is not None:
                values[name] = _to_value(member_shape, member)

        return values

    if kind == "list":
        return [_to_value(shape[1], item) for item in obj]

    if kind == "choice":
        return (obj._alternative, _to_value(shape[1][obj._alternative][1], obj.value))

    if kind == "enum":
        return obj.value if isinstance(obj, enum.Enum) else obj

    raise TypeError(shape)


def _from_value(shape: Any, value: Any) -> Any:
    """The object of given shape for what asnkitrt decoded."""

    if shape is None:
        return value

    if isinstance(shape, type):
        shape = getattr(shape, "_shape")

    kind = shape[0]

    if kind == "seq":
        arguments: dict[str, Any] = {{}}

        for attribute, name, member_shape, how in shape[2]:
            if how == "null":
                arguments[attribute] = name in value
            elif name in value:
                arguments[attribute] = _from_value(member_shape, value[name])
            elif how == "required_null":
                arguments[attribute] = None

        return shape[1](**arguments)

    if kind == "list":
        return [_from_value(shape[1], item) for item in value]

    if kind == "choice":
        alternative, shape_of_value = shape[1][value[0]]

        return alternative(_from_value(shape_of_value, value[1]))

    if kind == "enum":
        # An extensible enumeration is None for what it does not know of.
        if value is None:
            return None

        try:
            return shape[1](value)
        except ValueError:
            return value

    raise TypeError(shape)


def _alternatives(table: dict[str, Any]) -> dict[str, Any]:
    # The alternatives of a choice, which are not of one type.
    return table


def _encode(
    asn1_type: tuple[str, str],
    shape: Any,
    obj: Any,
    codec: CodecType,
    check_types: bool,
    check_constraints: bool,
) -> bytes:
    type_ = _type(codec, asn1_type)
    value = _to_value(shape, obj)

    if check_types:
        type_.check_types(value)

    if check_constraints:
        type_.check_constraints(value)

    return bytes(type_.encode(value))


def _decode(
    asn1_type: tuple[str, str],
    shape: Any,
    data: bytes | bytearray,
    codec: CodecType,
    check_constraints: bool,
) -> Any:
    type_ = _type(codec, asn1_type)
    value = type_.decode(data)

    if check_constraints:
        type_.check_constraints(value)

    return _from_value(shape, value)


class _Methods:
    """What the classes made from ASN.1 types can do."""

    _asn1_type: ClassVar[tuple[str, str]]
    _shape: ClassVar[Any]

    def to_value(self) -> Any:
        """What asnkitrt encodes for this object."""

        return _to_value(type(self)._shape, self)

    @classmethod
    def from_value(cls, value: Any) -> Any:
        """The object for what asnkitrt decoded."""

        return _from_value(cls._shape, value)

    def encode(
        self,
        codec: CodecType = DEFAULT_CODEC,
        check_types: bool = True,
        check_constraints: bool = False,
    ) -> bytes:
        """This object encoded with given codec."""

        return _encode(
            type(self)._asn1_type,
            type(self)._shape,
            self,
            codec,
            check_types,
            check_constraints,
        )

    @classmethod
    def decode(
        cls,
        data: bytes | bytearray,
        codec: CodecType = DEFAULT_CODEC,
        check_constraints: bool = False,
    ) -> Any:
        """The object that given data is when decoded with given codec."""

        return _decode(cls._asn1_type, cls._shape, data, codec, check_constraints)
'''


class Generator:
    def __init__(
        self,
        compiled: syntax.CompiledSpecification,
        asni: bytes,
        sources: list[str],
        codec: str,
        embed: bool = True,
    ) -> None:
        from asnkitrt.version import __version__ as asnkit_version  # noqa: F401

        from .version import __version__

        self.version = __version__
        self.asni = asni
        self.sources = sources
        self.codec = codec
        self.embed = embed
        self.modules: dict[str, Any] = syntax.compiled_to_dict(compiled)
        self.blocks: list[str] = []
        self.registrations: list[str] = []
        self.functions: list[str] = []
        self.exported: list[str] = ["DEFAULT_CODEC", "spec"]

        if not embed:
            self.exported.append("use_asni")
        self.taken: dict[str, str] = {name: "the code of the module" for name in TAKEN}
        self.names: dict[tuple[str, str], str] = {}
        self.aliases: dict[tuple[str, str], tuple[str, str]] = {}
        self.alias_blocks: list[str] = []

    # Names.

    def take(self, name: str, what: str) -> str:
        if name in self.taken:
            raise GenerateError(
                "Both {} and {} are called {} in Python.".format(
                    self.taken[name], what, name
                )
            )

        self.taken[name] = what

        return name

    def name_the_types(self) -> None:
        count: dict[str, int] = {}

        for module in self.modules.values():
            for type_name in module["types"]:
                count[camel(type_name)] = count.get(camel(type_name), 0) + 1

        for module_name, module in self.modules.items():
            for type_name in module["types"]:
                name = camel(type_name)

                if count[name] > 1:
                    # The same name in more than one module.
                    name = camel(module_name) + name

                if name in TAKEN:
                    name += "_"

                self.names[(module_name, type_name)] = self.take(
                    name, "the type {} of {}".format(type_name, module_name)
                )

    # Types.

    def lookup(self, module_name: str, type_name: str) -> Any:
        try:
            return self.modules[module_name]["types"][type_name]
        except KeyError:
            raise GenerateError(
                "The type {} of {} is not in the specification.".format(
                    type_name, module_name
                )
            )

    def kind_of(self, descriptor: dict[str, Any]) -> str:
        type_name = descriptor["type"]

        if type_name in ("SEQUENCE", "SET"):
            return "sequence"

        if type_name == "CHOICE":
            return "choice"

        if type_name == "ENUMERATED":
            return "enumerated"

        return "other"

    def resolves_to_null(self, descriptor: dict[str, Any], module_name: str) -> bool:
        seen = set()

        while True:
            type_name = descriptor["type"]
            module_name = descriptor.get("module-name", module_name)

            if type_name == "NULL":
                return True

            if (
                type_name in PLAIN_TYPES
                or type_name in ("SEQUENCE", "SET", "CHOICE", "ENUMERATED")
                or type_name.endswith(" OF")
                or "&" in type_name
                or (module_name, type_name) in seen
                or type_name not in self.modules.get(module_name, {}).get("types", {})
            ):
                return False

            seen.add((module_name, type_name))
            descriptor = self.lookup(module_name, type_name)

    def annotate(
        self, descriptor: dict[str, Any], module_name: str, context: str
    ) -> tuple[str, str]:
        """Returns the Python type of given type and its shape, and makes
        the classes it needs, named after the context if it has no name.

        """

        type_name = descriptor["type"]
        module_name = descriptor.get("module-name", module_name)

        if type_name in PLAIN_TYPES:
            return PLAIN_TYPES[type_name], "None"

        if "&" in type_name:
            # A field of an object class.
            return "Any", "None"

        if type_name in ("SEQUENCE", "SET"):
            name = self.take(camel(context), "the type in " + context)
            self.sequence(name, descriptor, module_name, None)

            return name, name

        if type_name == "CHOICE":
            name = self.take(camel(context), "the type in " + context)
            self.choice(name, descriptor, module_name, None)

            return name, name

        if type_name == "ENUMERATED":
            name = self.take(camel(context), "the type in " + context)
            self.enumerated(name, descriptor, module_name, None)

            return name, name

        if type_name in ("SEQUENCE OF", "SET OF"):
            element, shape = self.annotate(
                descriptor["element"], module_name, context + "-element"
            )

            return "list[{}]".format(element), '("list", {})'.format(shape)

        # The name of a type.
        key = (module_name, type_name)
        target = self.lookup(module_name, type_name)

        if self.kind_of(target) != "other":
            return self.names[key], self.names[key]

        return self.names[key], self.alias(key, target)[1]

    def alias(
        self, key: tuple[str, str], descriptor: dict[str, Any]
    ) -> tuple[str, str]:
        """The Python type and the shape of a type that is not a class of
        its own, which is made once.

        """

        if key not in self.aliases:
            # Not recursive, as only a class can refer to itself.
            self.aliases[key] = self.annotate(descriptor, key[0], self.names[key])

        return self.aliases[key]

    # Classes.

    def register(self, name: str, module_name: str, type_name: str, shape: str) -> None:
        self.registrations.append(
            "_register({}, ({!r}, {!r}), {})".format(
                name, module_name, type_name, shape
            )
        )

    def members(self, descriptor: dict[str, Any]) -> list[tuple[dict[str, Any], bool]]:
        """The members, with whether each is in an extension."""

        members: list[tuple[dict[str, Any], bool]] = []
        in_extension = False

        for member in descriptor["members"]:
            if member is None:
                in_extension = not in_extension
            elif isinstance(member, list):
                members.extend((item, True) for item in member)
            else:
                members.append((member, in_extension))

        return members

    def sequence(
        self,
        name: str,
        descriptor: dict[str, Any],
        module_name: str,
        type_name: str | None,
    ) -> None:
        lines = [
            "@dataclasses.dataclass(kw_only=True)",
            "class {}(_Methods):".format(name),
        ]
        fields = []
        attributes: dict[str, str] = {}

        scope = descriptor.get("module-name", module_name)

        for member, in_extension in self.members(descriptor):
            asn1_name = member["name"]
            attribute = field_name(asn1_name)

            if attribute in attributes:
                raise GenerateError(
                    "Both {} and {} of {} are called {} in Python.".format(
                        attributes[attribute], asn1_name, name, attribute
                    )
                )

            attributes[attribute] = asn1_name
            annotation, shape = self.annotate(member, scope, name + "-" + asn1_name)
            optional = in_extension or member.get("optional") or "default" in member
            null = self.resolves_to_null(member, scope)

            if optional and null:
                lines.append("    {}: bool = False".format(attribute))
                how = "null"
            elif null:
                lines.append("    {}: None = None".format(attribute))
                how = "required_null"
            elif optional:
                lines.append("    {}: {} | None = None".format(attribute, annotation))
                how = "optional"
            else:
                lines.append("    {}: {}".format(attribute, annotation))
                how = "required"

            fields.append(
                "({!r}, {!r}, {}, {!r})".format(attribute, asn1_name, shape, how)
            )

        if not attributes:
            lines.append("    pass")

        self.blocks.append("\n".join(lines))
        self.exported.append(name)
        shape = '("seq", {}, ({}))'.format(name, "".join(f + ", " for f in fields))
        self.register(name, module_name, type_name or "", shape)

    def choice(
        self,
        name: str,
        descriptor: dict[str, Any],
        module_name: str,
        type_name: str | None,
    ) -> None:
        self.blocks.append(
            "class {}(_Methods):\n    _alternative: ClassVar[str]".format(name)
        )
        self.exported.append(name)
        alternatives = []
        attributes: dict[str, str] = {}

        scope = descriptor.get("module-name", module_name)

        for member, _ in self.members(descriptor):
            asn1_name = member["name"]
            alternative = self.take(
                name + camel(asn1_name),
                "the alternative {} of {}".format(asn1_name, name),
            )
            annotation, shape = self.annotate(
                member, scope, name + "-" + asn1_name + "-value"
            )
            attributes[asn1_name] = alternative

            self.blocks.append(
                "@dataclasses.dataclass\n"
                "class {}({}):\n"
                "    value: {}\n"
                "    _alternative: ClassVar[str] = {!r}".format(
                    alternative, name, annotation, asn1_name
                )
            )
            self.exported.append(alternative)
            alternatives.append("{!r}: ({}, {}),".format(asn1_name, alternative, shape))

        shape = '("choice", _alternatives({{{}}}))'.format(" ".join(alternatives))
        self.register(name, module_name, type_name or "", shape)

    def enumerated(
        self,
        name: str,
        descriptor: dict[str, Any],
        module_name: str,
        type_name: str | None,
    ) -> None:
        lines = ["class {}(_Methods, enum.Enum):".format(name)]
        members: dict[str, str] = {}

        for value in descriptor["values"]:
            if value is None:
                continue

            asn1_name = value[0]
            member = snake(asn1_name).upper()

            if member in members:
                raise GenerateError(
                    "Both {} and {} of {} are called {} in Python.".format(
                        members[member], asn1_name, name, member
                    )
                )

            members[member] = asn1_name
            lines.append("    {} = {!r}".format(member, asn1_name))

        if not members:
            lines.append("    pass")

        self.blocks.append("\n".join(lines))
        self.exported.append(name)
        self.register(name, module_name, type_name or "", '("enum", {})'.format(name))

    # The whole module.

    def type_assignment(
        self, module_name: str, type_name: str, descriptor: dict[str, Any]
    ) -> None:
        name = self.names[(module_name, type_name)]
        kind = self.kind_of(descriptor)

        if kind == "sequence":
            self.sequence(name, descriptor, module_name, type_name)
        elif kind == "choice":
            self.choice(name, descriptor, module_name, type_name)
        elif kind == "enumerated":
            self.enumerated(name, descriptor, module_name, type_name)
        else:
            annotation, shape = self.alias((module_name, type_name), descriptor)
            function = snake(name)
            self.alias_blocks.append('{}: TypeAlias = "{}"'.format(name, annotation))
            self.exported.extend([name, "encode_" + function, "decode_" + function])
            self.functions.append(
                "def encode_{function}(\n"
                "    value: {name},\n"
                "    codec: CodecType = DEFAULT_CODEC,\n"
                "    check_types: bool = True,\n"
                "    check_constraints: bool = False,\n"
                ") -> bytes:\n"
                "    return _encode(\n"
                "        ({module!r}, {type!r}),\n"
                "        {shape},\n"
                "        value,\n"
                "        codec,\n"
                "        check_types,\n"
                "        check_constraints,\n"
                "    )\n\n\n"
                "def decode_{function}(\n"
                "    data: bytes | bytearray,\n"
                "    codec: CodecType = DEFAULT_CODEC,\n"
                "    check_constraints: bool = False,\n"
                ") -> {name}:\n"
                "    return _decode(\n"
                "        ({module!r}, {type!r}), {shape}, data, codec, check_constraints\n"
                "    )".format(
                    function=function,
                    name=name,
                    module=module_name,
                    type=type_name,
                    shape=shape,
                )
            )

    def run(self) -> str:
        self.name_the_types()

        for module_name, module in self.modules.items():
            for type_name, descriptor in module["types"].items():
                self.type_assignment(module_name, type_name, descriptor)

        # The classes made for types inside others have no name of their
        # own in the specification.
        header = HEADER.format(
            version=self.version,
            sources=", ".join(self.sources) or "a specification",
            codec=self.codec,
            load=(
                EMBEDDED.format(asni=format_bytes(self.asni))
                if self.embed
                else NOT_EMBEDDED
            ).strip("\n"),
        )
        parts = [
            header,
            "\n\n" + REGISTER,
            "\n\n\n".join(self.blocks),
            "\n".join(self.registrations),
            "\n".join(self.alias_blocks),
            "\n\n\n".join(self.functions),
            "__all__ = [\n{}]".format(
                "".join("    {!r},\n".format(name) for name in self.exported)
            ),
        ]

        return "\n\n\n".join(part.strip("\n") for part in parts if part.strip()) + "\n"


# How a module loads its specification when it is in it.
EMBEDDED = """\
# The compiled specification, as the contents of an .asni file.
_ASNI = (
{asni}
)


@functools.cache
def spec(codec: CodecType = DEFAULT_CODEC) -> asnkitrt.Specification:
    \"\"\"The specification, loaded for the given codec.\"\"\"

    return asnkitrt.load_asni(_ASNI, codec)
"""

# How a module loads its specification when it is not in it, but given
# by the code that uses it.
NOT_EMBEDDED = """\
# The compiled specification is not in this module: give it with use_asni().
_SPECIFICATION: asnkitrt.syntax.CompiledSpecification | None = None


def use_asni(
    data: bytes | bytearray,
    nonce: asnkitrt.syntax.NonceCheck = None,
    accept_any_nonce: bool = False,
    bound_to: str | None = None,
    accept_any_binding: bool = False,
    verification_keys: asnkitrt.syntax.Keys | None = None,
    accept_any_signature: bool = False,
    decryption_keys: asnkitrt.syntax.Keys | None = None,
) -> None:
    \"\"\"Uses the contents of an .asni file, made from the specification this
    module is made from, for all codecs. It is checked once, here, with the
    options of asnkitrt.load_asni().

    \"\"\"

    global _SPECIFICATION

    _SPECIFICATION = asnkitrt.syntax.from_asni(
        data,
        nonce,
        accept_any_nonce,
        bound_to,
        accept_any_binding,
        verification_keys,
        accept_any_signature,
        decryption_keys,
    )
    spec.cache_clear()


@functools.cache
def spec(codec: CodecType = DEFAULT_CODEC) -> asnkitrt.Specification:
    \"\"\"The specification given with use_asni(), loaded for the given codec.\"\"\"

    if _SPECIFICATION is None:
        raise RuntimeError("No specification: give it with use_asni().")

    return asnkitrt.load(_SPECIFICATION, codec)
"""


REGISTER = """\
def _register(
    class_: Any, asn1_type: tuple[str, str], shape: Any
) -> None:
    class_._asn1_type = asn1_type
    class_._shape = shape"""


def format_bytes(data: bytes) -> str:
    lines = []

    for offset in range(0, len(data), 24):
        chunk = data[offset : offset + 24]
        lines.append(
            '    b"{}"'.format("".join("\\x{:02x}".format(byte) for byte in chunk))
        )

    return "\n".join(lines) if lines else '    b""'


def generate(
    asni: bytes,
    sources: list[str] | None = None,
    codec: str = DEFAULT_CODEC,
    embed: bool = True,
) -> str:
    """Returns the text of a Python module for given contents of an
    ``.asni`` file, which must not be signed, encrypted, bound to
    something or have a nonce to check, as it may be embedded in the
    module and loaded without any of those. `sources` are the names of
    the files it was made from, and `codec` is what the module encodes
    and decodes with if not told otherwise. Without `embed`, the module
    does not have the specification in it, and is given it with its
    ``use_asni()``, as from a file that is signed or encrypted.

    """

    try:
        compiled = syntax.from_asni(asni)
    except Exception as error:
        raise GenerateError(
            "Expected a compiled specification that is not signed, encrypted, "
            "bound to something or has a nonce, but: {}".format(error)
        )

